const db = new PGlite();
await db.exec(`create schema storage; create table storage.buckets(id text primary key, public boolean, file_size_limit bigint, allowed_mime_types text[]);
insert into storage.buckets values ('scout-media',false,10485760,array['image/jpeg']),('other',true,42,array['application/pdf']);`);
await db.exec(sql);
await db.exec(sql);
const bucket = (await db.query("select * from storage.buckets where id='scout-media'")).rows[0];
assert.equal(bucket.public, false);
