assert.deepEqual(bucket.allowed_mime_types, ['image/jpeg','image/png','image/heic','image/heif','video/mp4','video/quicktime','video/x-m4v']);
const other = (await db.query("select * from storage.buckets where id='other'")).rows[0];
assert.equal(Number(other.file_size_limit),42);
assert.deepEqual(other.allowed_mime_types,['application/pdf']);
